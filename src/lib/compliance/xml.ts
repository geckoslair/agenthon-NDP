// The self-invoice draft as a small readable XML. SIMULATED: a demonstration draft with a
// simplified structure, not validated for tax purposes and never sent to a real authority.

export function escapeXml(value: string): string {
  return (
    value
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&apos;")
      // Characters not allowed in XML 1.0 are dropped.
      .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "")
  );
}

export interface SelfInvoiceXmlInput {
  docType: string;
  number: string;
  date: string;
  /** Deadline for sending, the 15th of the month after receipt (docs/domain.md). */
  deadline: string;
  company: { name: string; vatId: string };
  supplier: { name: string; country: string; taxId: string };
  original: {
    number: string;
    date: string;
    fileName: string;
    amount: number | null;
    currency: string;
  };
  taxableEur: number;
  vatRate: number;
  vatEur: number;
  totalEur: number;
}

const money = (n: number) => n.toFixed(2);

export function selfInvoiceXml(x: SelfInvoiceXmlInput): string {
  const t = (tag: string, value: string, indent = "  ") =>
    `${indent}<${tag}>${escapeXml(value)}</${tag}>`;
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!--",
    "  BOZZA DIMOSTRATIVA, NON VALIDATA FISCALMENTE. Simulated self-invoice draft generated by",
    "  Probata with a simplified structure. It is not a valid electronic invoice and no real tax",
    "  authority is contacted. Assumptions to be confirmed by the accountant: document type TD17",
    "  for services purchased from abroad; aliquota ordinaria 22%: da confermare; sending",
    "  deadline the 15th of the month after receipt.",
    "-->",
    "<AutofatturaSimulata>",
    t("TipoDocumento", x.docType),
    t("Numero", x.number),
    t("Data", x.date),
    t("ScadenzaInvio", x.deadline),
    "  <Emittente>",
    t("Denominazione", x.company.name, "    "),
    t("PartitaIVA", x.company.vatId, "    "),
    "  </Emittente>",
    "  <Destinatario>",
    t("Denominazione", x.company.name, "    "),
    t("PartitaIVA", x.company.vatId, "    "),
    "  </Destinatario>",
    "  <FornitoreEstero>",
    t("Denominazione", x.supplier.name, "    "),
    t("Paese", x.supplier.country, "    "),
    t("IdFiscale", x.supplier.taxId, "    "),
    "  </FornitoreEstero>",
    "  <FatturaOriginale>",
    t("Numero", x.original.number, "    "),
    t("Data", x.original.date, "    "),
    t("File", x.original.fileName, "    "),
    `    <Importo valuta="${escapeXml(x.original.currency)}">${x.original.amount === null ? "" : money(x.original.amount)}</Importo>`,
    "  </FatturaOriginale>",
    t("ImponibileEUR", money(x.taxableEur)),
    t("AliquotaIVA", money(x.vatRate)),
    t("ImpostaEUR", money(x.vatEur)),
    t("TotaleEUR", money(x.totalEur)),
    "</AutofatturaSimulata>",
    "",
  ].join("\n");
}

/** Reads the text of the first <tag>...</tag>; null when absent. Used by the SdI mock. */
export function readTag(xml: string, tag: string): string | null {
  const m = new RegExp(`<${tag}(?:\\s[^>]*)?>([^<]*)</${tag}>`).exec(xml);
  return m ? m[1].trim() : null;
}
